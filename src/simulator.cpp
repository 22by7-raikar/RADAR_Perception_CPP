#include "radar/simulator.hpp"

#include <cmath>
#include <stdexcept>

namespace radar {

Simulator::Simulator(const RadarConfig& radar, const SimulatorConfig& sim)
    : radar_(radar), sim_(sim), rng_(sim.seed) {
  radar_.validate();
}

double Simulator::echo_amplitude(const Target& target) const {
  if (target.range_m <= 0.0) throw std::invalid_argument("Target range must be positive");
  const double range_ratio = sim_.reference_range_m / target.range_m;
  const double snr_db = sim_.reference_snr_db + (target.rcs_dbsm - sim_.reference_rcs_dbsm) +
                        40.0 * std::log10(range_ratio);
  const double noise = radar_.noise_power > 0.0 ? radar_.noise_power : 1.0;
  return std::sqrt(noise * std::pow(10.0, snr_db / 10.0));
}

DataCube Simulator::simulate_frame(const std::vector<Target>& targets) {
  DataCube cube;
  simulate_frame(targets, cube);
  return cube;
}

void Simulator::simulate_frame(const std::vector<Target>& targets, DataCube& out) {
  const std::size_t nch = radar_.num_virtual();
  const std::size_t nd = radar_.chirps_per_frame;
  const std::size_t nr = radar_.samples_per_chirp;
  out.resize(nch, nd, nr);

  const double c = kSpeedOfLight;
  const double fc = radar_.carrier_hz;
  const double slope = radar_.slope();
  const double dt = 1.0 / radar_.sample_rate();
  const double tp = radar_.chirp_period();
  const double tl = radar_.loop_period();
  const double lambda = radar_.wavelength();

  for (const Target& tgt : targets) {
    const double amp = echo_amplitude(tgt);
    const double u = std::cos(tgt.elevation_rad) * std::sin(tgt.azimuth_rad);
    const double w_el = std::sin(tgt.elevation_rad);
    for (std::size_t k = 0; k < nch; ++k) {
      // Elements further along the target direction receive earlier.
      const ArrayElement p = radar_.virtual_position(k);
      const double array_delay = lambda * (p.y * u + p.z * w_el) / c;
      const double tx_offset = static_cast<double>(k / radar_.num_rx) * tp;
      for (std::size_t m = 0; m < nd; ++m) {
        const double t_chirp = static_cast<double>(m) * tl + tx_offset;
        // tau(t) = a + b t is linear in fast time, so the dechirped phase
        //   fc tau + S t tau - S tau^2 / 2  =  c0 + c1 t + c2 t^2
        // is quadratic and can be generated by a second-order phasor
        // recurrence: two complex multiplies per sample instead of sin/cos.
        const double a = 2.0 * (tgt.range_m + tgt.velocity_mps * t_chirp) / c - array_delay;
        const double b = 2.0 * tgt.velocity_mps / c;
        double c0 = fc * a - 0.5 * slope * a * a;
        const double c1 = (fc * b + slope * a - slope * a * b) * dt;  // cycles / sample
        const double c2 = (slope * b - 0.5 * slope * b * b) * dt * dt;
        c0 -= std::floor(c0);

        auto phasor = [](double cycles) {
          cycles -= std::floor(cycles);
          return std::polar(1.0, 2.0 * kPi * cycles);
        };
        std::complex<double> z = amp * phasor(c0);
        std::complex<double> w = phasor(c1 + c2);  // z[n+1] / z[n] at n = 0
        const std::complex<double> q = phasor(2.0 * c2);

        cfloat* row = &out(k, m, 0);
        for (std::size_t n = 0; n < nr; ++n) {
          row[n] += cfloat(static_cast<float>(z.real()), static_cast<float>(z.imag()));
          z *= w;
          w *= q;
        }
      }
    }
  }

  if (sim_.add_noise && radar_.noise_power > 0.0) {
    std::normal_distribution<float> noise(0.0f,
                                          static_cast<float>(std::sqrt(radar_.noise_power / 2.0)));
    cfloat* p = out.data();
    for (std::size_t i = 0; i < out.size(); ++i) p[i] += cfloat(noise(rng_), noise(rng_));
  }
}

}  // namespace radar
